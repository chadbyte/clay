var fs = require('fs');
var path = require('path');
var esbuild = require('esbuild');
// A2UI uses Zod's v3 API. Use the maintained v3 compatibility export in v4.
esbuild.build({
  entryPoints: [path.join(__dirname, '../lib/a2ui/frame.mjs')],
  outfile: path.join(__dirname, '../lib/public/a2ui/runtime.js'),
  banner: { js: '// Generated from lib/a2ui/frame.mjs. Third-party notices: LICENSES/a2ui.txt.' },
  bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true, metafile: true,
  legalComments: 'eof', plugins: [{ name: 'zod-compat', setup: function (build) {
    build.onResolve({ filter: /^zod$/ }, function () { return { path: require.resolve('zod/v3') }; });
  } }],
}).then(function (result) {
  var packages = new Map();
  Object.keys(result.metafile.inputs).forEach(function (input) {
    if (input.indexOf('node_modules/') === -1) return;
    var directory = path.dirname(path.resolve(input));
    while (!fs.existsSync(path.join(directory, 'package.json'))) directory = path.dirname(directory);
    var pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
    // Zod has subpath package metadata; retain its root license.
    while (!pkg.name) {
      directory = path.dirname(directory);
      if (fs.existsSync(path.join(directory, 'package.json'))) pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
    }
    packages.set(pkg.name, { directory: directory, pkg: pkg });
  });
  var notices = ['Bundled A2UI renderer and dependencies. Generated by scripts/build-a2ui.js.'];
  Array.from(packages.keys()).sort().forEach(function (name) {
    var item = packages.get(name);
    var files = fs.readdirSync(item.directory).filter(function (file) { return /^(LICENSE|COPYING|NOTICE)(\.|$)/i.test(file); });
    if (!files.length) throw new Error('Missing license for ' + name);
    notices.push('\n=== ' + name + '@' + item.pkg.version + ' (' + item.pkg.license + ') ===\n');
    files.forEach(function (file) { notices.push(fs.readFileSync(path.join(item.directory, file), 'utf8')); });
  });
  fs.writeFileSync(path.join(__dirname, '../LICENSES/a2ui.txt'), notices.join('\n') + '\n');
  var crypto = require('crypto');
  var dir = path.join(__dirname, '../lib/public/a2ui');
  var hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, 'runtime.js'))).update(fs.readFileSync(path.join(dir, 'frame.css'))).digest('hex').slice(0, 16);
  fs.writeFileSync(path.join(dir, 'version.js'), "export var runtimeVersion = '" + hash + "';\n");
}).catch(function (error) { console.error(error); process.exitCode = 1; });
