var yoke = require("./yoke");
var permissionModes = require("./session-permission-mode");

// Shared session effects. Callers authorize the exact live session before entry.
function attachSessionActions(ctx) {
  var sm = ctx.sm;
  function exact(session) {
    if (!session || sm.sessions.get(session.localId) !== session) throw new Error("Session was deleted or replaced.");
  }
  function rename(session, title) {
    exact(session);
    var previous = { title: session.title, titleProvisional: session.titleProvisional, titleAutoGenerated: session.titleAutoGenerated, titleManuallySet: session.titleManuallySet };
    session.title = title;
    session.titleProvisional = false;
    session.titleAutoGenerated = false;
    session.titleManuallySet = true;
    try { if (sm.saveSessionFile(session) === false) throw new Error("Could not save session title."); }
    catch (error) { Object.assign(session, previous); throw error; }
    sm.notifySessionRenamed(session.localId);
    sm.broadcastSessionList();
    var adapter = ctx.adapters && ctx.adapters[session.vendor] || ctx.adapter;
    if (session.cliSessionId && adapter && adapter.renameSession) {
      Promise.resolve(adapter.renameSession(session.cliSessionId, title, { dir: ctx.cwd, linuxUser: ctx.getLinuxUserForSession && ctx.getLinuxUserForSession(session) || undefined })).catch(function (error) {
        console.error("[session-actions] Provider title sync failed:", error.message);
      });
    }
    return { title: title };
  }
  function stop(session, actor) {
    exact(session);
    session._humanStopRevision = (session._humanStopRevision || 0) + 1;
    if (ctx.autonomousRun && session.autonomousRun) ctx.autonomousRun.finish(session, "stopped", "Stopped by the user.");
    if (typeof ctx.sdk.cancelResponseRecovery === "function") ctx.sdk.cancelResponseRecovery(session);
    session._pendingMessageDrainPaused = true;
    if (ctx.onPendingQueuePause) ctx.onPendingQueuePause(session, actor || null);
    if (!session.isProcessing && !session._queryStarting && !session._responseRecoveryStopPending) return { status: "completed", queuePaused: true };
    if (ctx.onHumanPairStop) ctx.onHumanPairStop(session);
    session.taskStopRequested = true;
    if (session.abortController) session.abortController.abort();
    return { status: "queued", queuePaused: true, detail: "Stop requested; runtime completion is still pending." };
  }
  async function effort(session, value, revalidate) {
    exact(session);
    var vendor = session.vendor || sm.defaultVendor || "claude";
    if (yoke.clampEffort(vendor, value) !== value) throw new Error("This effort level is not supported by the selected vendor.");
    var result = await ctx.sdk.setEffort(session, value, revalidate ? { revalidate: revalidate } : undefined);
    if (revalidate) return result;
    sm.sendToSession(session, { type: "config_state", sessionId: session.localId, vendor: vendor, effort: value, model: session.model || ((sm.defaultModelByVendor || {})[vendor]) || "", mode: session.permissionMode || sm.currentPermissionMode || "default", betas: sm.currentBetas || [], thinking: sm.currentThinking || "adaptive", thinkingBudget: sm.currentThinkingBudget || 10000 });
    return { effort: value };
  }
  async function permission(session, value, requestId, revalidate) {
    exact(session);
    if ((session.runtimeMode || session.mode || "gui") !== "gui" || ctx.isDriverOperatedSession && ctx.isDriverOperatedSession(session)) throw new Error("Permissions require a GUI Driver session.");
    if (ctx.dangerouslySkipPermissions) throw new Error("Skip permissions is forced by the server setting.");
    var valid = permissionModes.validate(session, value, sm.defaultVendor);
    if (!valid.ok) throw new Error(valid.error);
    if (session.permissionMode === "bypassPermissions" && valid.mode !== "bypassPermissions" && ctx.autonomousRun) await ctx.autonomousRun.stopForPermissionChange(session);
    var result = await ctx.fullAccessService.setMode(session, valid.mode, revalidate ? { revalidate: revalidate } : undefined);
    if (revalidate) return result;
    var state = permissionModes.clientState(session, sm.currentPermissionMode, sm.defaultVendor);
    sm.sendToSession(session, Object.assign({ type: "config_state", sessionId: session.localId, vendor: session.vendor || sm.defaultVendor || "claude", mode: state.requestedPermissionMode, permissionRequestId: requestId || null, effort: session.effort || sm.currentEffort || "medium", betas: sm.currentBetas || [] }, state));
    return state;
  }
  return { rename: rename, stop: stop, effort: effort, permission: permission };
}
module.exports = { attachSessionActions: attachSessionActions };
