// Coordinates bounded semantic title generation for completed conversations.

var titlePolicy = require("./session-title-policy");

var MAX_ATTEMPTS = 3;
var DEFAULT_REQUEST_TIMEOUT_MS = 20000;
var DEFAULT_COOLDOWN_MS = 60 * 1000;

function isWorker(session) {
  return !!(session && session.sessionProvenance && session.sessionProvenance.kind === "worker");
}

function hasUserMessage(session) {
  var history = session && Array.isArray(session.history) ? session.history : [];
  for (var i = 0; i < history.length; i++) {
    if (history[i] && history[i].type === "user_message" && typeof history[i].text === "string" && history[i].text.trim()) return true;
  }
  return false;
}

function attachSessionTitleGenerator(ctx) {
  var sm = ctx.sm;
  var getAdapter = ctx.getAdapter;
  var getLinuxUser = ctx.getLinuxUser || function () { return null; };
  var getRuntimeEnv = ctx.getRuntimeEnv || function () { return process.env; };
  var cwd = ctx.cwd;
  var now = ctx.now || function () { return Date.now(); };
  var scheduleTimeout = ctx.setTimeout || setTimeout;
  var cancelTimeout = ctx.clearTimeout || clearTimeout;
  var requestTimeoutMs = ctx.requestTimeoutMs || DEFAULT_REQUEST_TIMEOUT_MS;
  var cooldownMs = ctx.cooldownMs || DEFAULT_COOLDOWN_MS;
  var maxAttempts = ctx.maxAttempts || MAX_ATTEMPTS;

  function isLive(session) {
    if (!session || session.destroying || isWorker(session)) return false;
    if (!sm || !sm.sessions || typeof sm.sessions.get !== "function") return true;
    return sm.sessions.get(session.localId) === session;
  }

  function messagesFor(session) {
    var result = [];
    var history = Array.isArray(session.history) ? session.history : [];
    for (var i = 0; i < history.length; i++) {
      var entry = history[i];
      if (entry && entry.type === "user_message" && entry.text) {
        result.push(entry.text.substring(0, 200));
        if (result.length >= 5) break;
      }
    }
    return result;
  }

  // A bounded burst of attempts fails together (e.g. a provider outage);
  // suppressing forever would leave the session mistitled permanently.
  // Once the cooldown elapses, generate() allows a fresh burst instead.
  function beginCooldownIfExhausted(session) {
    if ((session._autoTitleAttempts || 0) >= maxAttempts && !session._autoTitleCooldownUntil) {
      session._autoTitleCooldownUntil = now() + cooldownMs;
    }
  }

  // A stuck legacy title from before bounded recovery existed (a rendered
  // provider auth-failure string, saved back when generation did not
  // validate its response) is narrowly repaired so a later completed turn
  // can retry. This never overwrites session.title itself; it only clears
  // the flag that was blocking a fresh attempt.
  function repairKnownFailedTitle(session) {
    if (isLive(session) && !session.titleManuallySet && session.titleAutoGenerated && titlePolicy.isFailedGeneratedTitle(session)) {
      session.titleAutoGenerated = false;
    }
  }

  function generate(session) {
    repairKnownFailedTitle(session);
    if (!isLive(session) || session.titleManuallySet || session.titleAutoGenerated || !hasUserMessage(session)) return false;
    if (session._autoTitleInFlight) return false;
    if ((session._autoTitleAttempts || 0) >= maxAttempts) {
      if (session._autoTitleCooldownUntil && now() < session._autoTitleCooldownUntil) return false;
      session._autoTitleAttempts = 0;
      session._autoTitleCooldownUntil = null;
    }
    var sessionAdapter = getAdapter(session);
    if (!sessionAdapter || typeof sessionAdapter.generateTitle !== "function") return false;
    var messages = messagesFor(session);
    if (!messages.length) return false;

    // Identifies this exact attempt so a late response arriving after this
    // attempt has already been decided (by timeout or otherwise) cannot
    // clobber whichever newer attempt may since have taken ownership.
    var token = {};
    session._autoTitleToken = token;
    session._autoTitleInFlight = true;
    session._autoTitleAttempts = (session._autoTitleAttempts || 0) + 1;
    var requestTitle = session.title;
    var controller = typeof AbortController === "function" ? new AbortController() : null;
    var timer = null;

    // The request and the bound race independently; whichever settles
    // first decides this attempt. An adapter that never honors the abort
    // signal and never settles still lets this attempt (and the Promise
    // generate() returns) resolve to a bounded failure, instead of hanging
    // forever and leaving _autoTitleInFlight stuck.
    var timeoutPromise = new Promise(function (resolve) {
      timer = scheduleTimeout(function () {
        if (controller) controller.abort();
        resolve({ timedOut: true });
      }, requestTimeoutMs);
      if (timer && typeof timer.unref === "function") timer.unref();
    });

    var requestPromise = Promise.resolve().then(function () {
      return sessionAdapter.generateTitle(messages, {
        cwd: cwd,
        linuxUser: getLinuxUser(session) || undefined,
        env: getRuntimeEnv(session),
        model: session.model || undefined,
        signal: controller ? controller.signal : undefined,
      });
    }).then(function (title) {
      return { timedOut: false, title: title };
    }, function (error) {
      return { timedOut: false, error: error };
    });
    // The loser of the race (usually the abandoned request after a
    // timeout) is left to settle on its own; it is never awaited or acted
    // on again, so its eventual value can never reach session.title.

    return Promise.race([timeoutPromise, requestPromise]).then(function (outcome) {
      cancelTimeout(timer);
      var owns = session._autoTitleToken === token;
      if (owns) session._autoTitleInFlight = false;

      if (outcome.timedOut) {
        if (owns) beginCooldownIfExhausted(session);
        return false;
      }
      if (outcome.error) {
        console.error("[auto-title] Failed:", outcome.error.message || outcome.error);
        if (owns) beginCooldownIfExhausted(session);
        return false;
      }
      var title = typeof outcome.title === "string" ? outcome.title.trim() : "";
      if (title.length < 2) { // Empty/near-empty is a failed attempt; the provisional title is preserved.
        if (owns) beginCooldownIfExhausted(session);
        return false;
      }
      title = title.substring(0, 100);
      if (!owns || !isLive(session) || session.titleManuallySet || session.titleAutoGenerated || session.title !== requestTitle) return false;
      session.title = title;
      session.titleProvisional = false;
      session.titleAutoGenerated = true;
      sm.saveSessionFile(session);
      sm.broadcastSessionList();
      if (session.cliSessionId && typeof sessionAdapter.renameSession === "function") {
        return Promise.resolve(sessionAdapter.renameSession(session.cliSessionId, title, { dir: cwd })).then(function () { return true; });
      }
      return true;
    }).catch(function (e) {
      // generate() is called fire-and-forget by callers (onAutoTitle does
      // not await or catch it), so a rejection here (a thrown save/broadcast,
      // or a rejected provider rename after the title was already applied
      // in memory) must be bounded here rather than becoming an unhandled
      // rejection. The title already applied above is left in place.
      console.error("[auto-title] Failed:", e.message || e);
      return false;
    });
  }

  return { generate: generate, maxAttempts: maxAttempts };
}

module.exports = { attachSessionTitleGenerator: attachSessionTitleGenerator };
