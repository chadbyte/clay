var test = require('node:test'), assert = require('node:assert/strict');
var path = require('path'), fork = require('child_process').fork, chromium = require('playwright').chromium;
test('project sidebar discloses worktrees explicitly and recovery checks/reviews the verified parent', { timeout: 90000 }, async function (t) {
  var child = fork(path.join(__dirname, 'fixtures/server-settings-server.js'), ['--project-tree'], { stdio: ['ignore', 'ignore', 'pipe', 'ipc'] });
  t.after(function () { child.kill('SIGTERM'); });
  var url = await new Promise(function (resolve, reject) { child.on('message', function (msg) { if (msg.port) resolve('http://127.0.0.1:' + msg.port); }); child.on('error', reject); });
  var browser = await chromium.launch(); t.after(function () { return browser.close(); }); var context = await browser.newContext({ viewport: { width: 1280, height: 800 } }); var page = await context.newPage(); page.setDefaultTimeout(10000);
  var errors = []; page.on('pageerror', function (error) { errors.push(error.message); });
  await page.goto(url + '/__fixture/admin');
  await page.locator('#title-bar-project-dropdown').click(); await page.getByRole('menuitem', { name: 'Project Settings', exact: true }).click();
  var tree = page.locator('#settings-project-tree');
  await tree.getByRole('button', { name: 'Expand Sample worktrees' }).waitFor();
  assert.equal(await tree.getByRole('button', { name: 'one worktree', exact: true }).isVisible(), false);
  assert.equal(await tree.getByRole('button', { name: 'Needs recovery project', exact: true }).isVisible(), true);
  await page.getByRole('button', { name: 'Manage access and ownership', exact: true }).click();
  await page.locator('.ps-access-member input').uncheck();
  await tree.getByRole('button', { name: 'Public sample project', exact: true }).click();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  assert.equal(await page.locator('.ps-access-member input').isChecked(), false);
  await fetch(url + '/__fixture/fail');
  await page.getByRole('button', { name: 'Save allowed users', exact: true }).click();
  await page.locator('.ps-access-editor .settings-status').filter({ hasText: 'draft is retained' }).waitFor();
  assert.equal(await page.locator('.ps-access-member input').isChecked(), false);
  await fetch(url + '/__fixture/recover');
  await page.getByRole('button', { name: 'Save allowed users', exact: true }).click();
  await page.getByRole('button', { name: 'Manage access and ownership', exact: true }).waitFor();
  var savedAccess = await (await fetch(url + '/__fixture/state')).json(); assert.deepEqual(savedAccess.projectAccess.sample.allowedUsers, []);
  await tree.getByRole('button', { name: 'Expand Sample worktrees' }).click();
  await tree.getByRole('button', { name: 'one worktree', exact: true }).click();
  await page.locator('#ps-target-title').filter({ hasText: 'one' }).waitFor();
  await page.getByRole('button', { name: 'Manage parent access', exact: true }).waitFor();
  assert.match(await page.locator('#ps-access-management').textContent(), /Inherited from sample/);
  assert.match(page.url(), /\/p\/sample\//);
  await tree.getByRole('button', { name: 'Collapse Sample worktrees' }).click();
  assert.equal(await tree.getByRole('button', { name: 'one worktree', exact: true }).isVisible(), false);
  var overview = await page.context().newPage();
  await overview.goto(url + '/p/orphan/');
  await overview.locator('#access-tab').click();
  await overview.locator('#overview-ownership-recovery').filter({ hasText: 'cannot be resolved' }).waitFor();
  assert.equal(await overview.locator('#messages, #input').count(), 0);
  await overview.close();
  await tree.getByRole('button', { name: 'Needs recovery project', exact: true }).click();
  await page.locator('#ps-ownership-recovery').filter({ hasText: 'cannot be resolved' }).waitFor();
  assert.equal(await page.locator('#project-settings [data-section=profile]').isVisible(), false);
  assert.equal(await page.locator('#project-settings [data-section=environment]').isVisible(), false);
  assert.equal(await page.getByRole('button', { name: 'Review recovery', exact: true }).count(), 0);
  await fetch(url + '/__fixture/verify-mapping');
  await page.getByRole('button', { name: 'Check again', exact: true }).click();
  await page.getByRole('button', { name: 'Review recovery', exact: true }).click();
  await fetch(url + '/__fixture/fail'); await page.getByRole('button', { name: 'Recover ownership', exact: true }).click();
  await page.locator('#ps-ownership-recovery').filter({ hasText: 'disk failure' }).waitFor();
  await fetch(url + '/__fixture/recover'); await page.getByRole('button', { name: 'Check again', exact: true }).click();
  await page.getByRole('button', { name: 'Review recovery', exact: true }).click(); await page.getByRole('button', { name: 'Recover ownership', exact: true }).click();
  await page.locator('#ps-ownership-recovery').filter({ hasText: 'Ownership recovered for Admin' }).waitFor();
  var state = await (await fetch(url + '/__fixture/state')).json(); assert.equal(state.projects[0].ownerId, 'admin');
  await tree.getByRole('button', { name: 'Sample project', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await tree.isVisible(), true);
  assert.equal(await tree.evaluate(function (el) { return el.scrollWidth <= el.clientWidth; }), true);
  assert.equal(await page.locator('#settings-shell-content').evaluate(function (el) { return el.scrollWidth <= el.clientWidth; }), true);
  await tree.getByRole('searchbox').fill('public'); assert.equal(await tree.getByRole('button', { name: 'Public sample project' }).isVisible(), true);
  await tree.getByRole('searchbox').fill('');
  await page.locator('#settings-shell-close').click();
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.locator('#title-bar-project-dropdown').click(); await page.getByRole('menuitem', { name: 'Project Settings', exact: true }).click();
  assert.equal(await tree.getByRole('button', { name: 'Expand Sample worktrees' }).getAttribute('aria-expanded'), 'false');
  await page.request.put(url + '/api/admin/projects/sample/users', { data: { allowedUsers: ['member'] } });
  await page.request.put(url + '/api/admin/users/member/permissions', { data: { permissions: { projectSettings: true } } });
  var memberContext = await browser.newContext(); var memberPage = await memberContext.newPage();
  await memberPage.goto(url + '/__fixture/member');
  await memberPage.waitForFunction(async function () { var m = await import('/modules/store.js'); return m.store.get('connected') && m.store.get('permissions') && m.store.get('permissions').projectSettings; });
  await memberPage.locator('#title-bar-project-dropdown').click(); await memberPage.getByRole('menuitem', { name: 'Project Settings', exact: true }).click();
  await memberPage.getByRole('button', { name: 'Expand Sample worktrees' }).click(); await memberPage.getByRole('button', { name: 'one worktree', exact: true }).click();
  await memberPage.locator('#ps-access-management').filter({ hasText: 'Inherited from sample' }).waitFor();
  assert.equal(await memberPage.getByRole('button', { name: 'Manage access and ownership', exact: true }).count(), 0);
  await memberContext.close();
  assert.deepEqual(errors, []);
});
