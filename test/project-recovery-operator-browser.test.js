var test = require('node:test'), assert = require('node:assert/strict');
var path = require('path'), fork = require('child_process').fork, chromium = require('playwright').chromium;
test('restricted project retains Settings and recovers with a reviewed local operator approval', { timeout: 90000 }, async function (t) {
  var child = fork(path.join(__dirname, 'fixtures/server-settings-server.js'), ['--project-tree', '--operator-recovery', '--only-orphan'], { stdio: ['ignore', 'ignore', 'pipe', 'ipc'] });
  t.after(function () { child.kill('SIGTERM'); });
  var url = await new Promise(function (resolve, reject) { child.on('message', function (msg) { if (msg.port) resolve('http://127.0.0.1:' + msg.port); }); child.on('error', reject); });
  var browser = await chromium.launch(); t.after(function () { return browser.close(); });
  var page = await browser.newPage({ viewport: { width: 1280, height: 800 } }); page.setDefaultTimeout(15000);
  var errors = []; page.on('pageerror', function (error) { errors.push(error.stack); });
  await page.goto(url + '/__fixture/admin'); await page.goto(url + '/p/orphan/');
  assert.equal(await page.locator('#messages, #input').count(), 0);
  await page.getByRole('link', { name: 'Open Server Settings' }).click();
  await page.locator('#settings-shell:not(.hidden)').waitFor();
  await page.locator('#server-settings:not(.hidden)').waitFor();
  await page.goto(url + '/p/orphan/');
  await page.getByRole('button', { name: 'Recover ownership', exact: true }).click();
  await page.locator('#overview-ownership-recovery').filter({ hasText: 'No verified account' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.getByRole('link', { name: 'Open Server Settings' }).isVisible(), true);
  assert.equal(await page.locator('#main-area').evaluate(function (el) { return el.scrollWidth <= el.clientWidth; }), true);
  assert.equal(await page.getByLabel('Approval code').isVisible(), true);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByLabel('Approval code').fill('0'.repeat(48));
  await page.getByRole('button', { name: 'Review server approval' }).click();
  await page.getByRole('status').filter({ hasText: 'Approval is invalid' }).waitFor();
  var issued = await new Promise(function (resolve) { child.once('message', resolve); child.send({ cmd: 'approve-recovery' }); });
  assert.equal(issued.ok, true);
  await page.getByLabel('Approval code').fill(issued.approvalCode);
  await page.getByRole('button', { name: 'Review server approval' }).click();
  await page.getByText('Proposed recovery owner: Admin', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Approval code').count(), 0);
  var state = await (await fetch(url + '/__fixture/state')).json(); assert.equal(state.projects[0].ownerId, 'removed');
  await page.getByRole('button', { name: 'Review recovery', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  state = await (await fetch(url + '/__fixture/state')).json(); assert.equal(state.projects[0].ownerId, 'removed');
  await page.getByRole('button', { name: 'Review recovery', exact: true }).click();
  await page.getByRole('button', { name: 'Recover ownership', exact: true }).last().click();
  await page.getByRole('status').filter({ hasText: 'Ownership recovered for Admin' }).waitFor();
  state = await (await fetch(url + '/__fixture/state')).json(); assert.equal(state.projects[0].ownerId, 'admin');
  await page.getByRole('button', { name: 'Reload project' }).click();
  await page.locator('#input').waitFor();
  assert.deepEqual(errors, []);
});
