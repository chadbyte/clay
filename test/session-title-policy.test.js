test("title provenance survives fresh storage roundtrip", function (t) {
  var root = fs.mkdtempSync(path.join(os.tmpdir(), "clay-title-roundtrip-"));
  t.after(function () { fs.rmSync(root, { recursive: true, force: true }); });
  var options = {
    cwd: path.join(root, "project"),
    sessionsBase: path.join(root, "sessions"),
    cliSessionsDir: path.join(root, "cli"),
    send: function () {},
  };
  var first = createSessionManager(options);
  var provisional = first.createSessionRaw({ cliSessionId: "provisional", vendor: "claude" });
  provisional.title = "First message label";
  provisional.titleProvisional = true;
  var generated = first.createSessionRaw({ cliSessionId: "generated", vendor: "codex" });
  generated.title = "Generated topic";
  generated.titleAutoGenerated = true;
  var manual = first.createSessionRaw({ cliSessionId: "manual", vendor: "claude" });
  manual.title = "Pinned name";
  manual.titleManuallySet = true;
  first.saveSessionFile(provisional);
  first.saveSessionFile(generated);
  first.saveSessionFile(manual);

  var second = createSessionManager(options);
  var restored = Array.from(second.sessions.values());
  var byId = function (id) { return restored.filter(function (session) { return session.cliSessionId === id; })[0]; };
  assert.equal(byId("provisional").titleProvisional, true);
  assert.equal(byId("generated").titleAutoGenerated, true);
  assert.equal(byId("manual").titleManuallySet, true);
  assert.equal(byId("manual").titleProvisional, false);
  assert.equal(policy.selectInitialTitle(byId("provisional"), "ignored").provisional, true);
  assert.equal(policy.selectInitialTitle(byId("generated"), "ignored").provisional, false);
  assert.equal(policy.selectInitialTitle(byId("manual"), "ignored").provisional, false);
});

test("unknown legacy titles remain protected and are not rewritten", function (t) {
  var root = fs.mkdtempSync(path.join(os.tmpdir(), "clay-title-legacy-"));
  t.after(function () { fs.rmSync(root, { recursive: true, force: true }); });
  var cwd = path.join(root, "project");
  var encoded = require("../lib/utils").encodeCwd(cwd);
  var sessionsDir = path.join(root, "sessions", encoded);
  fs.mkdirSync(sessionsDir, { recursive: true });
  fs.writeFileSync(path.join(sessionsDir, "legacy.jsonl"), [
    JSON.stringify({ type: "meta", localId: 1, cliSessionId: "legacy", title: "Custom legacy name", createdAt: 1 }),
    JSON.stringify({ type: "user_message", text: "A historical request" }),
  ].join("\n") + "\n");
  var manager = createSessionManager({ cwd: cwd, sessionsBase: path.join(root, "sessions"), cliSessionsDir: path.join(root, "cli"), send: function () {} });
  var restored = Array.from(manager.sessions.values())[0];
  assert.equal(restored.title, "Custom legacy name");
  assert.equal(restored.titleProvisional, false);
  assert.equal(restored.titleAutoGenerated, false);
  assert.equal(restored.titleManuallySet, true);
  assert.equal(policy.selectInitialTitle(restored, "ignored").provisional, false);
});

test("completed turns retry recorded OAuth error titles but preserve manual titles", function () {
  var calls = 0;
  var processor = titleProcessor(false, function () { calls++; });
  var session = completedSession();
  session.titleAutoGenerated = true;
  session.title = "Failed to authenticate: OAuth session expired and could not be refreshed";
  processor.processSDKMessage(session, { yokeType: "result" });
  assert.equal(calls, 1);
  session.titleManuallySet = true;
  processor.processSDKMessage(session, { yokeType: "result" });
  assert.equal(calls, 1);
  session.titleManuallySet = false;
  session.title = "Authentication failure investigation";
  processor.processSDKMessage(session, { yokeType: "result" });
  assert.equal(calls, 1);
});
