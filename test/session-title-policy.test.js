test("global-search titles use the visible query instead of provider boilerplate", function () {
  var transport = "This conversation began in Clay Studio's global search. Respond as Clay. User request: Find fruit";
  var apples = policy.selectInitialTitle({
    history: [{ type: "user_message", text: "Find my conversation about apple harvest planning" }],
  }, transport);
  var invoices = policy.selectInitialTitle({
    history: [{ type: "user_message", text: "Find the discussion about overdue client invoices" }],
  }, transport);

  assert.equal(apples.title, "Find my conversation about apple harvest planning");
  assert.equal(invoices.title, "Find the discussion about overdue client invoices");
  assert.notEqual(apples.title, invoices.title);
  assert.equal(apples.provisional, true);
});

