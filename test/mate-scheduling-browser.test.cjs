var test = require('node:test');
var assert = require('node:assert/strict');
var spawn = require('node:child_process').spawn;
var chromium = require('playwright').chromium;

test('production cards and WebSocket approvals: creation, existing Mate, reconnect, management, dispatch and privacy', async function (t) {
  var server = spawn(process.execPath, ['test/fixtures/mate-scheduling-browser-server.cjs', '0'], { cwd: require('path').resolve(__dirname, '..'), stdio: ['ignore', 'pipe', 'pipe'] });
  var browser;
  t.after(async function () { if (browser) await browser.close(); if (server.exitCode === null) { server.kill('SIGTERM'); await new Promise(function (resolve) { server.on('exit', resolve); }); } });
  var output = '';
  var url = await new Promise(function (resolve, reject) {
    var timeout = setTimeout(function () { reject(new Error(output || 'Fixture startup timed out.')); }, 20000);
    server.stdout.on('data', function (chunk) { output += chunk; var match = output.match(/http:\/\/127\.0\.0\.1:\d+/); if (match) { clearTimeout(timeout); resolve(match[0]); } });
    server.stderr.on('data', function (chunk) { output += chunk; });
    server.on('exit', function (code) { clearTimeout(timeout); reject(new Error('Fixture exit ' + code + ': ' + output)); });
  });
  browser = await chromium.launch({ headless: true });
  var page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  var errors = [];
  page.on('pageerror', function (error) { errors.push(error.message); });
  await page.goto(url);
  await page.getByRole('button', { name: 'Review new Mate', exact: true }).click();
  await page.getByRole('button', { name: 'Create Mate', exact: true }).waitFor();
  var summary = page.locator('.home-mate-proposal-schedule-summary');
  assert.equal(await summary.innerText(), 'January 1, 2031 at 9 AM: Send my creation-time briefing');
  var exact = page.locator('.home-mate-proposal-schedule-details');
  assert.equal(await exact.getAttribute('open'), null);
  await exact.locator('summary').focus();
  await page.keyboard.press('Enter');
  assert.equal(await exact.evaluate(function (element) { return element.open; }), true);
  assert.match(await exact.innerText(), /January 1, 2031 at 09:00 \(UTC\)/);
  await page.keyboard.press('Enter');
  assert.equal(await exact.evaluate(function (element) { return element.open; }), false);
  var touch = await browser.newPage({ viewport: { width: 390, height: 800 }, hasTouch: true });
  await touch.goto(url);
  var touchExact = touch.locator('.home-mate-proposal-schedule-details');
  await touchExact.locator('summary').tap();
  assert.equal(await touchExact.evaluate(function (element) { return element.open; }), true);
  assert.match(await touchExact.innerText(), /January 1, 2031 at 09:00 \(UTC\)/);
  await touchExact.locator('summary').tap();
  assert.equal(await touchExact.evaluate(function (element) { return element.open; }), false);
  await touch.close();
  assert.equal(await page.evaluate(function () { return window.fixtureState.jobs.length; }), 0);
  await page.getByRole('button', { name: 'Create Mate', exact: true }).click();
  await page.waitForFunction(function () { return window.fixtureState.schedules.length === 1; });
  await page.getByRole('button', { name: 'Review existing Mate schedule', exact: true }).click();
  await page.getByRole('button', { name: 'Create schedule', exact: true }).click();
  assert.equal(await page.evaluate(function () { return window.fixtureState.jobs.length; }), 1);
  await page.getByRole('button', { name: 'Confirm choice', exact: true }).click();
  await page.waitForFunction(function () { return window.fixtureState.schedules.length === 2; });
  await page.getByRole('button', { name: 'Reconnect', exact: true }).click();
  await page.getByRole('button', { name: 'Update', exact: true }).first().click();
  await page.getByRole('button', { name: 'Update schedule', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm choice', exact: true }).click();
  await page.waitForFunction(function () { return window.fixtureState.schedules[0].rule.time === '10:30'; });
  await page.getByRole('button', { name: 'Read', exact: true }).first().click();
  await page.waitForFunction(function () { return window.fixtureState.results.some(function (result) { return result.schedule && result.schedule.rule.time === '10:30'; }); });
  await page.getByRole('button', { name: 'Dispatch due messages', exact: true }).click();
  await page.waitForFunction(function () { return window.fixtureState.dispatched === 1; });
  await page.getByRole('button', { name: 'Cancel schedule', exact: true }).first().click();
  await page.locator('.home-debate-question-option').filter({ hasText: 'Cancel schedule' }).click();
  await page.getByRole('button', { name: 'Confirm choice', exact: true }).click();
  await page.waitForFunction(function () { return window.fixtureState.schedules[0].state === 'cancelled'; });
  await page.reload();
  await page.waitForFunction(function () { return window.fixtureState && window.fixtureState.schedules[0].state === 'cancelled'; });
  var foreign = await browser.newPage();
  await foreign.goto(url + '/?foreign=1');
  await foreign.getByText('Owner access required.', { exact: true }).waitFor();
  assert.equal(await foreign.locator('#schedules li').count(), 0);
  assert.equal(await foreign.locator('.home-mate-proposal,.home-debate-question').count(), 0);
  assert.deepEqual(errors, []);
});
