var test = require('node:test');
var assert = require('node:assert/strict');
var cp = require('node:child_process');
var path = require('node:path');
var playwright = require('playwright');
var WebSocket = require('ws');

test('contextual Clay uses one production session through the presentation cycle', async function (t) {
  var child = cp.fork(path.join(__dirname, 'fixtures/contextual-clay-server.cjs'), [], { stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });
  var output = '';
  child.stdout.on('data', function (data) { output += data; }); child.stderr.on('data', function (data) { output += data; });
  t.after(function () { child.kill('SIGTERM'); });
  var info = await new Promise(function (resolve, reject) {
    var timer = setTimeout(function () { reject(new Error(output)); }, 15000);
    child.once('message', function (value) { clearTimeout(timer); resolve(value); });
    child.once('exit', function () { clearTimeout(timer); reject(new Error(output)); });
  });
  var browser = await playwright.chromium.launch();
  t.after(async function () { await browser.close(); });
  var page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  var errors = []; page.on('pageerror', function (error) { errors.push(error.message); });
  page.setDefaultTimeout(10000);
  var origin = 'http://127.0.0.1:' + info.port;
  var foreignStatus = await new Promise(function (resolve, reject) {
    var socket = new WebSocket(origin.replace('http', 'ws') + '/p/' + info.sourceSlug + '/ws?pane=1&contextual=1&session=' + info.sourceSessionId, { headers: { Cookie: 'relay_auth_user=fixture-foreign-token', Origin: origin } });
    socket.on('unexpected-response', function (request, response) { response.resume(); socket.terminate(); resolve(response.statusCode); });
    socket.on('error', function () {});
    socket.on('open', function () { socket.terminate(); reject(new Error('Foreign contextual viewer was accepted')); });
  });
  assert.equal(foreignStatus, 403);
  await page.goto(origin + '/fixture/login?to=alpha');
  var trigger = page.locator('.icon-strip-brand');
  await trigger.waitFor();
  await page.waitForFunction(function () { return !document.querySelector('.icon-strip-brand').disabled; });
  t.diagnostic('Project loaded');
  await trigger.click();
  var surface = page.locator('#contextual-clay');
  assert.equal(await surface.getAttribute('data-mode'), 'popover');
  var frame = page.frameLocator('#contextual-clay iframe');
  await frame.locator('#messages').getByText('Isolated canonical integration conversation.', { exact: true }).waitFor();
  t.diagnostic('Canonical history loaded');
  await frame.locator('#input').evaluate(function (element) { if (document.activeElement !== element) throw new Error('Ready composer did not receive initial focus'); });
  await frame.locator('#stt-btn-picker').click();
  await frame.locator('#speech-picker').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await frame.locator('#speech-picker').count(), 0);
  assert.equal(await surface.isVisible(), true, 'Escape dismisses the native voice menu before the popover');
  await surface.locator('.contextual-clay-context summary').click();
  await page.keyboard.press('Escape');
  assert.equal(await surface.isVisible(), true, 'Escape dismisses inner context disclosure first');
  assert.equal(await surface.locator('.contextual-clay-context').getAttribute('open'), null);
  await page.waitForFunction(function () {
    var anchor = document.querySelector('.icon-strip-brand').getBoundingClientRect();
    var surface = document.getElementById('contextual-clay').getBoundingClientRect();
    var hint = document.getElementById('contextual-mate-hint').getBoundingClientRect();
    return Math.abs(hint.left - anchor.right - 8) < 1 && surface.left >= hint.right + 7 && Math.abs(surface.top - anchor.top) < 1;
  });
  assert.equal(await surface.locator('[data-clay-loading]').isVisible(), false);
  assert.ok(await frame.locator('#messages > .msg-user').count() >= 2, 'Visual fixture contains multiple human turns');
  assert.equal(await frame.locator('body').evaluate(function (body) { return body.scrollWidth <= body.clientWidth; }), true, 'Long content stays inside the chat');
  assert.ok(await frame.locator('.msg-assistant .md-content').last().evaluate(function (element) { return parseFloat(getComputedStyle(element).fontSize); }) >= 15);
  await frame.locator('#messages').evaluate(function (element) { element.scrollTop = 0; });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-desktop-conversation.png' });
  await frame.locator('#messages').evaluate(function (element) { element.scrollTop = element.scrollHeight; });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-desktop-long-text.png' });
  await frame.locator('#input').fill('Preserved contextual draft');
  var childFrame = page.frames().find(function (item) { return item.url().includes('contextual=1'); });
  var original = await childFrame.evaluate(async function () {
    window.contextualMarker = 'same renderer';
    var module = await import('./modules/store.js');
    return { session: module.store.get('activeSessionId'), path: module.store.get('wsPath') };
  });
  assert.equal(original.session, info.sourceSessionId);
  assert.match(original.path, new RegExp('&session=' + info.sourceSessionId));
  var reference = await childFrame.evaluate(async function () { return (await import('./modules/contextual-clay-session.js')).contextualScreenReference(); });
  assert.match(reference, /Untrusted screen reference/);
  assert.match(reference, /"projectSlug":"alpha"/);
  await page.getByRole('button', { name: 'Close Clay conversation', exact: true }).click();
  await trigger.click();
  assert.equal(await frame.locator('#input').inputValue(), 'Preserved contextual draft');
  assert.equal(await childFrame.evaluate(function () { return window.contextualMarker; }), 'same renderer');
  var proposal = page.request.get(origin + '/fixture/propose?viewer=alpha&target=beta');
  await frame.getByText('Apply exact change', { exact: true }).waitFor();
  var review = frame.locator('.ask-user-container').last();
  await review.locator('.product-review-action').getByText('Open conversation: Beta destination', { exact: true }).waitFor();
  assert.equal(await review.locator('.product-review > p').first().textContent(), 'In beta, using the selected window currently connected to alpha.');
  assert.equal(await review.locator('.product-review details').getAttribute('open'), null);
  await review.scrollIntoViewIfNeeded();
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-desktop-review-summary.png' });
  await page.evaluate(async function () { (await import('/p/alpha/modules/theme.js')).applyTheme('clay-dark'); });
  await childFrame.evaluate(async function () { (await import('./modules/theme.js')).applyTheme('clay-dark'); });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-desktop-review-dark.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-narrow-review-dark.png' });
  await page.evaluate(async function () { (await import('/p/alpha/modules/theme.js')).applyTheme('clay-light'); });
  await childFrame.evaluate(async function () { (await import('./modules/theme.js')).applyTheme('clay-light'); });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-narrow-review-summary.png' });
  await review.locator('.product-review summary').click();
  assert.equal(await review.locator('.product-review pre').evaluate(function (element) { return element.scrollWidth <= element.clientWidth && element.getBoundingClientRect().right <= window.innerWidth; }), true);
  await page.setViewportSize({ width: 1280, height: 800 });
  assert.match(await review.locator('.product-review pre').textContent(), /Selected viewer:.*viewer:/);
  assert.match(await review.locator('.product-review pre').textContent(), /"projectSlug":"beta"/);
  assert.equal(await review.locator('.product-review pre').evaluate(function (element) { return element.scrollWidth <= element.clientWidth; }), true);
  var reviewId = await frame.locator('.ask-user-container').last().getAttribute('data-tool-id');
  await frame.locator('.ask-user-container').last().scrollIntoViewIfNeeded();
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-desktop-review.png' });
  await page.getByRole('button', { name: 'Close Clay conversation', exact: true }).click();
  await trigger.click();
  assert.equal(await frame.locator('.ask-user-container').last().getAttribute('data-tool-id'), reviewId);
  await frame.getByText('Keep unchanged', { exact: true }).click();
  await frame.locator('.ask-user-submit').click();
  assert.equal((await (await proposal).json()).status, 'cancelled');
  assert.equal(await review.locator('.ask-user-answer-label').textContent(), 'Open conversation');
  await page.request.get(origin + '/fixture/stream');
  async function checkRunningControls() {
    await frame.locator('#generation-stop').waitFor({ state: 'visible' });
    var rects = await childFrame.evaluate(function () {
      return ['generation-stop', 'stt-btn', 'send-btn'].map(function (id) { var r = document.getElementById(id).getBoundingClientRect(); return { id: id, left: r.left, right: r.right, top: r.top, bottom: r.bottom }; });
    });
    for (var i = 1; i < rects.length; i++) assert.ok(rects[0].right <= rects[i].left || rects[0].left >= rects[i].right || rects[0].bottom <= rects[i].top || rects[0].top >= rects[i].bottom, 'Stop has a separate slot: ' + JSON.stringify(rects));
  }
  await checkRunningControls();
  await frame.locator('#messages').getByText('CONTEXTUAL_STREAM_CONTINUES', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Close Clay conversation', exact: true }).click();
  assert.equal(page.url(), origin + '/p/alpha/');
  await trigger.click();
  await page.getByRole('button', { name: 'Close Clay conversation', exact: true }).click();
  assert.equal(await trigger.evaluate(function (element) { return document.activeElement === element; }), true);
  await trigger.click();
  await frame.locator('#input').focus(); await page.keyboard.press('Escape');
  assert.equal(await surface.isVisible(), false);
  assert.equal(await trigger.evaluate(function (element) { return document.activeElement === element; }), true);
  await trigger.click(); await page.mouse.click(950, 350);
  assert.equal(await surface.isVisible(), false);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await trigger.click();
  var multiline = 'Help me organise this project. Keep my current session open while we review the next steps.';
  await frame.locator('#input').fill(multiline);
  await frame.locator('#input').evaluate(function (element) { element.setSelectionRange(21, 21); });
  await page.setViewportSize({ width: 390, height: 844 });
  await checkRunningControls();
  await childFrame.waitForFunction(function () { var input = document.getElementById('input'); return input.scrollHeight <= input.clientHeight + 1; });
  assert.equal(await frame.locator('#input').inputValue(), multiline);
  assert.equal(await frame.locator('#input').evaluate(function (element) { return element.selectionStart; }), 21);
  await frame.locator('#input').fill(Array(20).fill(multiline).join('\n'));
  await childFrame.waitForFunction(function () { var input = document.getElementById('input'); return getComputedStyle(input).overflowY === 'auto' && input.scrollHeight > input.clientHeight && input.getBoundingClientRect().height <= 121; });
  await frame.locator('#input').fill('Preserved contextual draft');
  var bounds = await surface.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  assert.equal(await frame.locator('body').evaluate(function (body) { return body.scrollWidth <= body.clientWidth; }), true);
  assert.equal(await surface.evaluate(function (element) { return getComputedStyle(element).transitionDuration; }), '0s');
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-narrow-conversation.png' });
  await page.evaluate(async function () { (await import('/p/alpha/modules/theme.js')).applyTheme('clay-dark'); });
  await childFrame.evaluate(async function () { (await import('./modules/theme.js')).applyTheme('clay-dark'); });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-narrow-dark.png' });
  await page.evaluate(async function () { (await import('/p/alpha/modules/theme.js')).applyTheme('clay-light'); });
  await childFrame.evaluate(async function () { (await import('./modules/theme.js')).applyTheme('clay-light'); });
  assert.equal(await frame.locator('#input').inputValue(), 'Preserved contextual draft');
  await page.setViewportSize({ width: 1280, height: 800 });
  await childFrame.evaluate(async function () { window.contextualWs = await import('./modules/ws-ref.js'); window.contextualStore = (await import('./modules/store.js')).store; window.previousContextualSocket = window.contextualWs.getWs(); window.previousContextualSocket.close(); });
  await childFrame.waitForFunction(function () { return window.contextualWs.getWs() !== window.previousContextualSocket && window.contextualStore.get('contextualSessionReady') === true; });
  assert.equal(await childFrame.evaluate(async function () { return (await import('./modules/store.js')).store.get('activeSessionId'); }), info.sourceSessionId);
  assert.equal(await frame.locator('#input').inputValue(), 'Preserved contextual draft');
  await page.evaluate(function () {
    window.contextualActivity = [];
    new MutationObserver(function (mutations) {
      mutations.forEach(function (mutation) { mutation.addedNodes.forEach(function (node) { if (node.id === 'clay-control-activity') window.contextualActivity.push({ text: node.textContent, pointer: node.classList.contains('has-target') }); }); });
    }).observe(document.body, { childList: true });
  });
  await childFrame.evaluate(async function () {
    window.reviewSends = [];
    var ws = (await import('./modules/ws-ref.js')).getWs(); var send = ws.send.bind(ws);
    ws.send = function (value) { window.reviewSends.push(JSON.parse(value)); return send(value); };
  });
  assert.equal(await frame.locator('#input').inputValue(), 'Preserved contextual draft');
  var approved = page.request.get(origin + '/fixture/propose?viewer=alpha&target=beta');
  await childFrame.waitForFunction(function (previousId) { return Array.from(document.querySelectorAll('.ask-user-container:not(.answered)')).some(function (element) { return element.dataset.toolId !== previousId; }); }, reviewId);
  await frame.locator('.ask-user-container:not(.answered)').last().getByText('Apply exact change', { exact: true }).click();
  await frame.locator('.ask-user-container:not(.answered) .ask-user-submit').click();
  var submitted = await (await page.request.get(origin + '/fixture/state')).json();
  var observedSends = await childFrame.evaluate(function () { return window.reviewSends; });
  assert.deepEqual(submitted.sessions.find(function (item) { return item.id === info.sourceSessionId; }).pending, [], 'Review must be answered: ' + JSON.stringify({ state: submitted, sends: observedSends }));
  assert.equal((await (await approved).json()).status, 'delivered');
  await page.waitForURL('**/p/beta/');
  await page.locator('#messages').getByText('BETA_RENDERED_DESTINATION', { exact: true }).waitFor();
  assert.equal(await surface.isVisible(), false);
  assert.deepEqual(await page.evaluate(function () { return window.contextualActivity; }), [{ text: 'I’m opening the reviewed conversation.', pointer: false }]);
  assert.equal(await page.locator('#clay-control-activity').count(), 0);
  await page.evaluate(async function (sessionId) {
    var activity = await import('/p/alpha/modules/clay-control-activity.js');
    activity.showClayNavigationActivity({ projectSlug: 'beta', sessionId: sessionId }, false);
  }, submitted.betaSessionId);
  assert.equal(await page.locator('#clay-control-activity').evaluate(function (element) { return getComputedStyle(element).pointerEvents; }), 'none');
  assert.equal(await page.locator('#clay-control-activity').getAttribute('class'), 'has-target');
  await page.locator('.session-item[data-session-id="' + submitted.betaSessionId + '"]').evaluate(function (row) { row.remove(); });
  await page.waitForFunction(function () { return !document.getElementById('clay-control-activity'); });
  await trigger.focus(); await page.keyboard.press('Enter');
  assert.equal(await frame.locator('#input').evaluate(function (element) { return element === document.activeElement; }), true);
  assert.equal(await childFrame.evaluate(function () { return window.contextualMarker; }), 'same renderer');
  assert.equal(await frame.locator('#input').inputValue(), 'Preserved contextual draft');
  await page.getByRole('button', { name: 'Close Clay conversation', exact: true }).click();
  assert.equal(await surface.isVisible(), false);
  await trigger.click();
  await page.request.get(origin + '/fixture/remove-contextual-session');
  await childFrame.evaluate(async function () { (await import('./modules/ws-ref.js')).getWs().close(); });
  await frame.locator('#contextual-session-warning').waitFor();
  await childFrame.waitForFunction(function () { return window.contextualStore.get('connected') && document.getElementById('connect-overlay').classList.contains('hidden'); });
  await page.screenshot({ animations: 'disabled', path: '/tmp/contextual-clay-unavailable.png' });
  assert.equal(await frame.locator('#input-wrapper').evaluate(function (element) { return element.inert; }), true);
  assert.deepEqual(errors, []);
});
